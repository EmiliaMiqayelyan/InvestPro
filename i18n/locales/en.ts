type DeepStringify<T> = {
  [K in keyof T]: T[K] extends string
    ? string
    : T[K] extends ReadonlyArray<infer U>
      ? ReadonlyArray<DeepStringify<U>>
      : T[K] extends object
        ? DeepStringify<T[K]>
        : T[K];
};

